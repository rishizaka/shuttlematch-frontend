import { formatJapaneseDate } from './date'

export type ReleaseTag = '新機能' | '改善' | '不具合修正'

export type ReleaseNote = {
  /** URL スラッグ。詳細ページは /release/{id} */
  id: string
  /** 公開日 (JST) 'YYYY-MM-DD' */
  date: string
  title: string
  /** 一覧カードに表示する 1〜2 文の要約 */
  summary: string
  tags: ReleaseTag[]
  /**
   * 見出し画像(任意)。一覧のサムネイル・詳細ページの見出し・SNS 共有時の og:image に使う。
   * サイト全体では og:image を出さない方針(試合表のリンクで画像がノイズになる)だが、
   * リリース告知は共有されて嬉しいページなので、ここだけは例外にしている。
   */
  hero?: {
    /** 詳細ページと og:image 用(1200px 幅) */
    src: string
    /** 一覧のサムネイル用(640px 幅) */
    thumb: string
    alt: string
    /** 読み込み前のレイアウトずれを防ぐための実寸 */
    width: number
    height: number
  }
  /**
   * 詳細ページの本文。heading を省略したセクションは地の文として表示する。
   * bullets は paragraphs のあとに箇条書きで並ぶ(細かい修正をまとめて挙げるとき用)。
   */
  sections: Array<{ heading?: string; paragraphs: string[]; bullets?: string[] }>
}

