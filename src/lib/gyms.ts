export type GymReview = {
  /** URL スラッグ。詳細ページは /gym/{id} */
  id: string
  /** 執筆日 (JST) 'YYYY-MM-DD' */
  date: string
  /** 施設の正式名称 */
  name: string
  prefecture: string
  city: string
  /** わかる範囲の住所。番地まで含める。 */
  address: string
  /** 最寄り駅・駐車場など */
  access: string
  /** バドミントンで使えるコート数(公式サイトに明記が無い場合は運営者が現地で数えた数) */
  courtCount: number
  /** 施設の公式ページ。料金・予約方法・休館日は変わりうるので本文では概算に留め、ここへ誘導する。 */
  officialUrl: string
  /** 一覧カードの要約・meta description に使う。検索結果に出る文なので1〜2文で要点を書く。 */
  summary: string
  /**
   * 本文。heading を省略したセクションは地の文として表示する。guides.ts と同じ形。
   */
  sections: Array<{ heading?: string; paragraphs: string[]; bullets?: string[] }>
}

